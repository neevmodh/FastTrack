// Minimal, dependency-free RFC4180-ish CSV parser. Handles quoted fields,
// commas/newlines inside quotes, and escaped quotes ("" -> "). Deliberately
// small and auditable rather than pulling in a third-party parser for
// untrusted file uploads.
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let inQuotes = false;

  const pushField = () => {
    row.push(field);
    field = "";
  };
  const pushRow = () => {
    pushField();
    rows.push(row);
    row = [];
  };

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const next = text[i + 1];

    if (inQuotes) {
      if (char === '"' && next === '"') {
        field += '"';
        i++;
      } else if (char === '"') {
        inQuotes = false;
      } else {
        field += char;
      }
      continue;
    }

    if (char === '"') {
      inQuotes = true;
    } else if (char === ",") {
      pushField();
    } else if (char === "\r") {
      // skip, handled by \n
    } else if (char === "\n") {
      pushRow();
    } else {
      field += char;
    }
  }

  // last field/row if the file doesn't end with a newline
  if (field.length > 0 || row.length > 0) pushRow();

  return rows.filter((r) => r.some((cell) => cell.trim().length > 0));
}
